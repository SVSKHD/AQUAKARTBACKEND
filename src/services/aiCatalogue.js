import AquaProduct from "../models/product.js";

// The storefront assistant recommends from the live catalogue, so it names real
// products (the storefront turns those names into product cards) and can tell
// automatic softeners from manual ones. Rebuilt at most every few minutes.
const CACHE_MS = 10 * 60 * 1000;
const MAX_PRODUCTS = 60;

const stripHtml = (s) =>
  String(s || "")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/<[^>]+>/g, " ")
    .replace(/\s+/g, " ")
    .trim();

const cleanTitle = (t) =>
  String(t || "")
    .replace(/\s*\|\s*aquakart\s*$/i, "")
    .trim();

const inr = (n) => `₹${Math.round(Number(n) || 0).toLocaleString("en-IN")}`;

// Facts a shopper compares softeners on, read from the title and description.
export const softenerFacts = (title, text) => {
  const all = `${title} ${text}`;
  const regen =
    /\bmanual\b/i.test(all) && !/\bautomatic\b|autosoftener/i.test(title)
      ? "manual (salt added and regenerated by hand)"
      : /automatic|autosoftener|auto[- ]?regenerat/i.test(all)
        ? "automatic (regenerates by itself)"
        : "";
  const resin = all.match(/resin volume\s*([\d.]+)\s*l/i)?.[1];
  const flow = all.match(
    /flow rate\s*(?:max\.?|up to)?\s*([\d,]+)\s*l\s*\/\s*h/i,
  )?.[1];
  const scope = /washing/i.test(title)
    ? "washing machine only"
    : /bathroom/i.test(title) || (resin && Number(resin) <= 8)
      ? "one bathroom"
      : /entire household|whole[- ]house|whole[- ]home/i.test(all) ||
          (resin && Number(resin) >= 20)
        ? "whole home"
        : "";
  return [
    regen,
    scope,
    resin && `resin ${resin} L`,
    flow && `flow up to ${flow.replace(/,/g, "")} L/hr`,
  ].filter(Boolean);
};

export const catalogueLine = (p) => {
  const title = cleanTitle(p.title);
  const category = p.category?.title || "";
  const price =
    p.discountPriceStatus && p.discountPrice ? p.discountPrice : p.price;
  const facts = /soft/i.test(`${category} ${title}`)
    ? softenerFacts(title, stripHtml(p.description))
    : [];
  const stock = p.stock === 0 ? "out of stock" : "in stock";
  return `- ${[title, category, inr(price), ...facts, stock].filter(Boolean).join(" | ")}`;
};

export const catalogueInstruction = (products) => {
  const lines = products
    .filter((p) => p?.title && Number(p.price) > 0)
    .slice(0, MAX_PRODUCTS)
    .map(catalogueLine);
  if (!lines.length) return "";
  return [
    "AquaKart catalogue (name | category | listed price | details | stock):",
    ...lines,
    "Recommend only products from this catalogue and write each one's name in bold exactly as listed.",
    "Prices are the listed prices; say the product page shows the current price and offers.",
    "For softeners always say whether each is automatic or manual, and whether it treats the whole home, one bathroom or only a washing machine.",
    "For a home with several bathrooms (a villa, duplex or independent house), compare a whole-home automatic softener sized for all bathrooms running together (a shower uses about 600 L/hr) with fitting a softener per bathroom, and suggest a hardness test and an AquaKart site visit to confirm the size.",
  ].join("\n");
};

let cache = { at: 0, text: "" };

export const getCatalogueInstruction = async (now = Date.now()) => {
  if (cache.text && now - cache.at < CACHE_MS) return cache.text;
  try {
    const products = await AquaProduct.find({})
      .select(
        "title price discountPrice discountPriceStatus stock description category",
      )
      .populate("category", "title")
      .lean();
    cache = { at: now, text: catalogueInstruction(products) };
  } catch (error) {
    console.error("AI catalogue load failed:", error);
    // Keep answering without the catalogue; try again on the next question.
    cache = { at: 0, text: cache.text };
  }
  return cache.text;
};

export const resetCatalogueCache = () => {
  cache = { at: 0, text: "" };
};
