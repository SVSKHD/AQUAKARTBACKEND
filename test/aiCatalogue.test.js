import test from "node:test";
import assert from "node:assert/strict";
import {
  catalogueInstruction,
  catalogueLine,
} from "../src/services/aiCatalogue.js";

const softeners = { title: "Softeners" };

test("softener lines say automatic or manual, what they treat, and their size", () => {
  assert.equal(
    catalogueLine({
      title: "Kent Automatic Water Softener 40 | Aquakart",
      category: softeners,
      price: 100000,
      discountPrice: 95000,
      discountPriceStatus: true,
      stock: 4,
      description:
        "Designed to convert hard water into soft water for your entire household. Resin Volume 40 L Flow Rate Up to 4000 L/hr",
    }),
    "- Kent Automatic Water Softener 40 | Softeners | ₹95,000 | automatic (regenerates by itself) | whole home | resin 40 L | flow up to 4000 L/hr | in stock",
  );
  assert.equal(
    catalogueLine({
      title: "Kent Bathroom Water Softener 5.5L | Aquakart",
      category: softeners,
      price: 18000,
      stock: 0,
      description:
        "Resin Volume 5.5 L. For flats &amp; individual bathrooms. Since this is a manual softener, add salt and regenerate.",
    }),
    "- Kent Bathroom Water Softener 5.5L | Softeners | ₹18,000 | manual (salt added and regenerated by hand) | one bathroom | resin 5.5 L | out of stock",
  );
  // "Unlike manual bathroom softeners" in an automatic unit's copy doesn't make it manual.
  assert.match(
    catalogueLine({
      title: "Kent Automatic 8L",
      category: softeners,
      price: 36000,
      description:
        "Unlike manual bathroom softeners, it adjusts to usage. Resin Volume 8 L Flow Rate 1200 L/H",
    }),
    /automatic \(regenerates by itself\) \| one bathroom \| resin 8 L \| flow up to 1200 L\/hr/,
  );
  assert.match(
    catalogueLine({
      title: "kent Washing Water Softener",
      category: softeners,
      price: 7000,
      description: "&lt;p&gt;For washing machines&lt;/p&gt;",
    }),
    /washing machine only/,
  );
});

test("the instruction lists products and asks for exact names; empty catalogue adds nothing", () => {
  const text = catalogueInstruction([
    {
      title: "RO + UV Purifier",
      category: { title: "Purifiers" },
      price: 15000,
    },
    { title: "Free sample", price: 0 },
  ]);
  assert.match(text, /- RO \+ UV Purifier \| Purifiers \| ₹15,000 \| in stock/);
  assert.doesNotMatch(text, /Free sample/);
  assert.match(text, /name in bold exactly as listed/);
  assert.equal(catalogueInstruction([]), "");
});
