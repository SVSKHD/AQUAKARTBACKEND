import test from "node:test";
import assert from "node:assert/strict";
import {
  catalogueInstruction,
  catalogueLine,
  boosterGuide,
  filterFacts,
  filterGuide,
  softenerFit,
  softenerGuide,
} from "../src/services/aiCatalogue.js";

const softeners = { title: "Softeners" };

test("softener lines say automatic or manual, what they treat, and their size", () => {
  assert.equal(
    catalogueLine({
      title: "Kent Automatic Water Softener 40 | Aquakart",
      category: softeners,
      price: 100000,
      discountPrice: 95000,
      discountPriceStatus: true,
      stock: 4,
      description:
        "Designed to convert hard water into soft water for your entire household. Resin Volume 40 L Flow Rate Up to 4000 L/hr",
    }),
    "- Kent Automatic Water Softener 40 | Softeners | ₹95,000 | automatic (regenerates by itself) | for whole home (villa, duplex or independent house) | resin 40 L | flow up to 4000 L/hr | in stock",
  );
  assert.equal(
    catalogueLine({
      title: "Kent Bathroom Water Softener 5.5L | Aquakart",
      category: softeners,
      price: 18000,
      stock: 0,
      description:
        "Resin Volume 5.5 L. For flats &amp; individual bathrooms. Since this is a manual softener, add salt and regenerate.",
    }),
    "- Kent Bathroom Water Softener 5.5L | Softeners | ₹18,000 | manual (salt added and regenerated by hand) | for one bathroom (flat or apartment) | resin 5.5 L | out of stock",
  );
  // "Unlike manual bathroom softeners" in an automatic unit's copy doesn't make it manual.
  assert.match(
    catalogueLine({
      title: "Kent Automatic 8L",
      category: softeners,
      price: 36000,
      description:
        "Unlike manual bathroom softeners, it adjusts to usage. Resin Volume 8 L Flow Rate 1200 L/H",
    }),
    /automatic \(regenerates by itself\) \| for one bathroom \(flat or apartment\) \| resin 8 L \| flow up to 1200 L\/hr/,
  );
  assert.match(
    catalogueLine({
      title: "kent Washing Water Softener",
      category: softeners,
      price: 7000,
      description: "&lt;p&gt;For washing machines&lt;/p&gt;",
    }),
    /washing machine only/,
  );
});

test("the instruction lists products and asks for exact names; empty catalogue adds nothing", () => {
  const text = catalogueInstruction([
    {
      title: "RO + UV Purifier",
      category: { title: "Purifiers" },
      price: 15000,
    },
    { title: "Free sample", price: 0 },
  ]);
  assert.match(text, /- RO \+ UV Purifier \| Purifiers \| ₹15,000 \| in stock/);
  assert.doesNotMatch(text, /Free sample/);
  assert.match(text, /name in bold exactly as listed/);
  assert.equal(catalogueInstruction([]), "");
});

// The live softener lineup, with sizes only in the titles.
const lineup = [
  { title: "Kent Washing Water Softener", price: 7000 },
  { title: "Kent Bathroom Water Softener 5.5L | Aquakart", price: 18000 },
  { title: "Kent Automatic 8L | Aquakart", price: 36000 },
  {
    title: "Kent Automatic Water Softener 25 | Aquakart",
    price: 70000,
    discountPrice: "65000",
    discountPriceStatus: true,
  },
  { title: "Kent Automatic Water Softener 40 | Aquakart", price: 100000 },
  { title: "Kent Automatic Water Softener 100L | Aquakart", price: 135000 },
].map((p) => ({ ...p, category: softeners, stock: 5 }));

test("softeners fall into one home group by their title size when the description has none", () => {
  assert.deepEqual(
    lineup.map((p) => softenerFit(p.title)),
    ["washing", "bathroom", "bathroom", "home", "home", "building"],
  );
  assert.equal(softenerFit("Auto 25"), "home");
  assert.equal(softenerFit("Unknown Softener"), null);
});

test("the villa group holds only the 25 and 40, and bold names are tied to recommendations", () => {
  assert.deepEqual(softenerGuide(lineup), [
    "Softeners by the home they suit (recommend only from the matching group):",
    "- washing machine only: Kent Washing Water Softener",
    "- one bathroom (flat or apartment): Kent Bathroom Water Softener 5.5L; Kent Automatic 8L",
    "- whole home (villa, duplex or independent house): Kent Automatic Water Softener 25; Kent Automatic Water Softener 40",
    "- large building (apartment block, hostel, hotel or commercial): Kent Automatic Water Softener 100L",
  ]);
  const text = catalogueInstruction(lineup);
  assert.match(
    text,
    /Kent Automatic Water Softener 25 \| Softeners \| ₹65,000 \| automatic/,
  );
  assert.match(
    text,
    /bold only the products you recommend, never a product you are ruling out/,
  );
  assert.match(text, /villa.*recommend only from the whole-home/);
  assert.match(text, /Terrace: .*pressure booster pump is needed/);
  assert.match(
    text,
    /customised pumps from 0\.7 to 0\.9 hp can also be ordered on demand/,
  );
  assert.match(
    text,
    /Ground level: fit a non-return valve \(NRV\).*regeneration isn't interrupted/,
  );
  assert.equal(softenerGuide([{ title: "RO Purifier", price: 1 }]).length, 0);
});

test("every pressure booster is listed, matched by category even with a misspelled title", () => {
  const pumps = { title: "Pressure Pumps" };
  const products = [
    {
      title: "Kent Pressure Bootser | Aquakart",
      category: pumps,
      price: 25000,
    },
    {
      title: "Grundfos 0.7hp Pressure Booster With 24Ltr Air tank | Aquakart",
      category: pumps,
      price: 70000,
    },
    {
      title: "RO + UV Purifier",
      category: { title: "Purifiers" },
      price: 15000,
    },
  ];
  assert.deepEqual(boosterGuide(products), [
    "Pressure boosters (listed): Kent Pressure Bootser; Grundfos 0.7hp Pressure Booster With 24Ltr Air tank",
  ]);
  assert.match(
    catalogueInstruction(products),
    /Pressure boosters \(listed\): Kent Pressure Bootser/,
  );
  assert.deepEqual(boosterGuide([products[2]]), []);
});

test("filters are grouped by problem: mud to sand filters, stains to the iron filter", () => {
  const filters = { title: "Filters" };
  const products = [
    {
      title: "kent Automatic Sandfilter 100L | Aquakart",
      category: filters,
      price: 65000,
    },
    {
      title: "Kent Iron Filter | Aquakart",
      category: filters,
      price: 32400,
      description: "Multiport valve for backwash",
    },
    { title: "Kent Sandfilter | Aquakart", category: filters, price: 24500 },
  ];
  assert.deepEqual(filterGuide(products), [
    "Filters by the water problem they solve (recommend only from the matching group):",
    "- mud, sand, silt or cloudy water: kent Automatic Sandfilter 100L; Kent Sandfilter",
    "- iron (orange or brown stains, metallic taste or smell): Kent Iron Filter",
  ]);
  assert.deepEqual(filterFacts("Kent Iron Filter", "Multiport valve"), [
    "manual backwash (multiport valve)",
    "for iron (orange or brown stains, metallic taste or smell)",
  ]);
  assert.match(
    catalogueLine(products[0]),
    /Filters \| ₹65,000 \| automatic backwash \| for mud, sand, silt or cloudy water \| in stock/,
  );
  const text = catalogueInstruction(products);
  assert.match(text, /recommended products up front, one line each/);
  assert.match(
    text,
    /all at once in one compact numbered block .* single reply/,
  );
  assert.match(
    text,
    /\nQuick questions:\n1\. Water source: borewell \/ tanker \/ municipal\n/,
  );
  assert.match(text, /sand filter goes first, then the iron filter/);
  // A softener is never treated as a filter.
  assert.deepEqual(
    filterGuide([
      {
        title: "Kent Automatic 8L",
        category: { title: "Softeners" },
        price: 1,
      },
    ]),
    [],
  );
});
